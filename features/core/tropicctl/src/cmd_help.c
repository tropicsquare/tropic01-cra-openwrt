/*
 * cmd_help.c -- `tropicctl help`, and the generated reference (markdown) and manual page (man). Everything is printed
 * from the command table plus the small tables below, so the documentation cannot drift from the code.
 */
#include <stdio.h>
#include <string.h>

#include "cmd_table.h"
#include "errors.h"
#include "output.h"

#ifndef TROPICCTL_VERSION
#define TROPICCTL_VERSION "0"
#endif

static const struct { const char *opt, *text; } GLOBALS[] = {
    {"--spi-dev PATH", "SPI device (default " TROPICCTL_SPI_DEV ", or $TROPICCTL_SPI_DEV)"},
    {"--gpio-dev PATH", "GPIO chip (default " TROPICCTL_GPIO_DEV ")"},
    {"--cs-pin N", "chip-select GPIO line (default " "25" ")"},
    {"--spi-speed HZ", "SPI clock (default " "1000000" ")"},
    {"--key SOURCE", "pairing key: auto (default), shared (the slot-0 key set by TROPICCTL_SH0 or <key dir>/slot0-key: es01 or prod0), es01, prod0, unit, file:PATH:SLOT, pin"},
    {"--pin-file FILE, --pin-stdin", "where a PIN comes from (never the command line); otherwise a terminal prompt"},
    {"--json", "machine-readable output on stdout; errors as a JSON object on stderr"},
    {"-q, -v", "quiet / verbose notices on stderr"},
    {"--lock-timeout SEC", "how long to wait for the chip lock (default 10)"},
    {"--dry-run", "check everything read-only, say what would be written, write nothing"},
    {"--no-lock", "do not take the chip lock (tests and debugging only)"},
    {"--version, -h", "print the version / this help"},
};

static const struct { int code; const char *text; } EXITS[] = {
    {TC_OK, "success"},
    {TC_INTERNAL, "internal error (a bug)"},
    {TC_USAGE, "usage error (bad arguments)"},
    {TC_UNREACHABLE, "chip unreachable or busy (SPI, GPIO, lock timeout)"},
    {TC_SESSION, "secure session failed (no usable pairing key, key refused)"},
    {TC_DENIED, "access denied by the chip's access rights"},
    {TC_NOTFOUND, "slot empty or object not found"},
    {TC_OCCUPIED, "slot already written"},
    {TC_VERIFY, "verification failed (read-back mismatch)"},
    {TC_REFUSED, "refused by a safety rule (missing confirmation flag, forbidden target)"},
    {TC_CHIP, "the chip reported another error"},
};

static const struct { char cls; const char *name, *text; } CLASSES[] = {
    {'R', "read-only", "changes nothing on the chip"},
    {'W', "reversible write", "can be undone by another command (an R-MEM slot, an ECC key)"},
    {'I', "irreversible", "cannot be undone; needs a named --yes-... flag"},
    {'H', "hazardous", "can leave the chip unusable if done wrong; needs a named --yes-... flag"},
};

void print_version(void) { printf("tropicctl %s\n", TROPICCTL_VERSION); }

static void text_overview(void)
{
	const char *area = "";
	printf("tropicctl %s -- command-line tool for the TROPIC01 secure element\n\n", TROPICCTL_VERSION);
	printf("Usage: tropicctl [global options] <area> <verb> [arguments]\n       tropicctl help [area [verb]]\n\n");
	printf("Commands (safety class in brackets: R read-only, W reversible write, I irreversible, H hazardous):\n");
	for (size_t i = 0; i < g_ncmds; i++) {
		if (strcmp(area, g_cmds[i].area) != 0) {
			area = g_cmds[i].area;
			printf("\n  %s\n", area);
		}
		printf("    %-8s [%c] %s\n", g_cmds[i].verb, g_cmds[i].cls, g_cmds[i].summary);
	}
	printf("\nGlobal options:\n");
	for (size_t i = 0; i < sizeof GLOBALS / sizeof GLOBALS[0]; i++) printf("  %-20s %s\n", GLOBALS[i].opt, GLOBALS[i].text);
	printf("\nStarted under the name lt-util the program runs in compatibility mode with the old command line.\n");
}

static void text_command(const cmd_t *c)
{
	printf("tropicctl %s %s %s\n\n  %s\n  Safety class: %c\n\n  %s\n", c->area, c->verb, c->usage, c->summary, c->cls, c->details);
}

static void markdown(void)
{
	const char *area = "";
	printf("# tropicctl reference\n\n_Generated by `tropicctl help --format markdown`; do not edit by hand._\n\n");
	printf("Usage: `tropicctl [global options] <area> <verb> [arguments]`\n\n## Safety classes\n\n| Class | Meaning |\n|---|---|\n");
	for (size_t i = 0; i < sizeof CLASSES / sizeof CLASSES[0]; i++)
		printf("| %c %s | %s |\n", CLASSES[i].cls, CLASSES[i].name, CLASSES[i].text);
	printf("\n## Global options\n\n| Option | Meaning |\n|---|---|\n");
	for (size_t i = 0; i < sizeof GLOBALS / sizeof GLOBALS[0]; i++) printf("| `%s` | %s |\n", GLOBALS[i].opt, GLOBALS[i].text);
	printf("\n## Exit codes\n\n| Code | Meaning |\n|---|---|\n");
	for (size_t i = 0; i < sizeof EXITS / sizeof EXITS[0]; i++) printf("| %d | %s |\n", EXITS[i].code, EXITS[i].text);
	printf("\n## Commands\n");
	for (size_t i = 0; i < g_ncmds; i++) {
		const cmd_t *c = &g_cmds[i];
		if (strcmp(area, c->area) != 0) {
			area = c->area;
			printf("\n### %s\n", area);
		}
		printf("\n#### `%s %s %s`\n\nClass **%c**. %s\n\n%s\n", c->area, c->verb, c->usage, c->cls, c->summary, c->details);
	}
}

static void man_escape(const char *s)
{
	for (; *s; s++) {
		if (*s == '-') fputs("\\-", stdout);
		else if (*s == '\\') fputs("\\\\", stdout);
		else fputc(*s, stdout);
	}
}

static void man(void)
{
	printf(".TH TROPICCTL 1 \"\" \"tropicctl %s\" \"User Commands\"\n.SH NAME\ntropicctl \\- command-line tool for the TROPIC01 secure element\n", TROPICCTL_VERSION);
	printf(".SH SYNOPSIS\n.B tropicctl\n[global options] <area> <verb> [arguments]\n.SH DESCRIPTION\nGenerated from the command table; see also the reference in the source tree.\n");
	printf(".SH GLOBAL OPTIONS\n");
	for (size_t i = 0; i < sizeof GLOBALS / sizeof GLOBALS[0]; i++) {
		printf(".TP\n.B ");
		man_escape(GLOBALS[i].opt);
		printf("\n");
		man_escape(GLOBALS[i].text);
		printf("\n");
	}
	printf(".SH COMMANDS\n");
	for (size_t i = 0; i < g_ncmds; i++) {
		const cmd_t *c = &g_cmds[i];
		printf(".TP\n.B %s %s\n", c->area, c->verb);
		man_escape(c->usage);
		printf("\n.br\n[%c] ", c->cls);
		man_escape(c->summary);
		printf(". ");
		man_escape(c->details);
		printf("\n");
	}
	printf(".SH EXIT STATUS\n");
	for (size_t i = 0; i < sizeof EXITS / sizeof EXITS[0]; i++) {
		printf(".TP\n.B %d\n", EXITS[i].code);
		man_escape(EXITS[i].text);
		printf("\n");
	}
}

int cmd_help(int argc, char **argv)
{
	const char *fmt = "text", *words[2] = {NULL, NULL};
	int nw = 0;
	for (int i = 0; i < argc; i++) {
		if (strcmp(argv[i], "--format") == 0 && i + 1 < argc) fmt = argv[++i];
		else if (nw < 2) words[nw++] = argv[i];
		else return out_error(TC_USAGE, "help takes at most an area and a verb");
	}
	if (strcmp(fmt, "markdown") == 0) { markdown(); return TC_OK; }
	if (strcmp(fmt, "man") == 0) { man(); return TC_OK; }
	if (strcmp(fmt, "text") != 0) return out_error(TC_USAGE, "unknown help format '%s' (text, markdown, man)", fmt);
	if (nw == 0) { text_overview(); return TC_OK; }
	if (nw == 2) {
		const cmd_t *c = cmd_find(words[0], words[1]);
		if (!c) return out_error(TC_USAGE, "unknown command '%s %s'", words[0], words[1]);
		text_command(c);
		return TC_OK;
	}
	for (size_t i = 0, found = 0; i < g_ncmds; i++) {
		if (strcmp(g_cmds[i].area, words[0]) != 0) continue;
		if (!found++) printf("tropicctl %s\n\n", words[0]);
		printf("  %-8s [%c] %s %s\n      %s\n", g_cmds[i].verb, g_cmds[i].cls, g_cmds[i].verb, g_cmds[i].usage, g_cmds[i].summary);
		if (i + 1 == g_ncmds || strcmp(g_cmds[i + 1].area, words[0]) != 0) return TC_OK;
	}
	return out_error(TC_USAGE, "unknown area '%s'", words[0]);
}
